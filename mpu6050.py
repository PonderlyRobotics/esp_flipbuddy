class MPU6050:
    """GY-521 MPU-6050 3-axis gyroscope and acceleration sensor"""

    def __init__(
        self,
        i2c,
        int_pin,
        addr=MPU6050_ADDR,
        calibrate=True,
        mean=None,
        stddev=None,
        enable_mpu=False,
    ):
        self._i2c = i2c
        self._int_pin = Pin(int_pin, Pin.IN, Pin.PULL_UP)
        self._addr = addr
        self.reset_mpu()
        self.angle_pitch = self.angle_roll = 0
        self.angle_pitch_output = self.angle_roll_output = 0
        self.set_gyro_angles = False
        self.sum = self.sum2 = [0, 0, 0, 0, 0, 0]
        self.mean = self.stddev = 0
        self._init()
        if calibrate:
            self.calibrate()
        else:
            self.mean = mean
            self.stddev = stddev

        self.irq_start(self.gyro)
        if enable_mpu:
            self.enable_dmp()

    def _init(self):
        """Init MPU6050"""
        # Power sensor
        self._i2c.writeto_mem(self._addr, MPU6050_PWR_MGMT_1, bytes([0]))
        # Set Digital Low Pass Filter (DLPF) 260Hz, Output rate 1kHz
        # self._i2c.writeto_mem(self._addr, MPU6050_CONFIG, bytes([6]))
        self._i2c.writeto_mem(self._addr, MPU6050_CONFIG, bytes([6]))
        # Set Sample Rate Divider at 64
        # Output rate: 1kHz / 64 = 15.625Hz
        # Output period: 1 / 15.625Hz = 64ms
        # self._i2c.writeto_mem(self._addr, MPU6050_SMPRT_DIV, bytes([63]))
        self._i2c.writeto_mem(self._addr, MPU6050_SMPRT_DIV, bytes([63]))
        period = 64 / 1000  # one measure every period in second
        gyro_lsb = 131  # Gyro LSB Sensitivity
        self.gyro_conv = period / gyro_lsb
        # Interrupt enable on data ready
        self._i2c.writeto_mem(self._addr, MPU6050_INT_ENABLE, bytes([1]))
        # Clear interrupt status to unlatch the interrupt pin
        self._i2c.readfrom_mem(self._addr, MPU6050_INT_STATUS, 1)

    def raw(self, _irq=None):
        """Get accel, temp and gyro raw data"""
        return unpack(
            ">hhhhhhh", self._i2c.readfrom_mem(self._addr, MPU6050_ACCEL_OUT, 14)
        )

    def raw_stdscr(self, _irq=None):
        """Get accel and gyro raw data normalize with standard score"""
        raw = list(self.raw())
        raw.pop(3)  # Pop temperature
        # Raw accel and standard score gyro
        _rms = zip(raw[3:6], self.mean[3:6], self.stddev[3:6])  # noqa: B905
        return raw[0:3] + [(r - m) / s for r, m, s in _rms]

    def calibrate(self, sample=50):
        """Calculate mean and standard deviation for accel and gyro"""
        self._i2c.writeto_mem(
            self._addr, MPU6050_USER_CTRL, b"\x00"
        )  # Disable DMP & FIFO
        self._i2c.writeto_mem(self._addr, MPU6050_FIFO_EN, b"\x00")  # Disable FIFO
        self._sample = 0
        self.sample = sample
        self.sum = self.sum2 = [0, 0, 0, 0, 0, 0]
        self.irq_start(self.mean_stddev)
        print("Calibrating", end="")
        while self._sample < self.sample:
            print(".", end="")
            sleep_ms(800)
        print()
        print("Calibration completed")
        print("    Mean:", self.mean)
        print("    StdDev:", self.stddev)

    def mean_stddev(self, _irq=None):
        """Calculate mean and standard deviation for accel and gyro"""
        raw_data = list(self.raw())
        raw_data.pop(3)  # Pop temperature
        self.sum = [rd + s for rd, s in zip(raw_data, self.sum)]  # noqa: B905
        self.sum2 = [rd**2 + s2 for rd, s2 in zip(raw_data, self.sum2)]  # noqa: B905
        self._sample += 1
        if self._sample >= self.sample:
            self.irq_stop()
            _p = self._sample
            self.mean = [s / _p for s in self.sum]
            self.stddev = [
                (s2 / _p - m**2) ** 0.5
                for m, s2 in zip(self.mean, self.sum2)  # noqa: B905
            ]

    def gyro(self, _irq=None):
        """update gyro pitch and roll"""
        raw_stdscr = self.raw_stdscr()
        accel_x, accel_y, _accel_z, gyro_x, gyro_y, gyro_z = raw_stdscr
        accel_vector = sum(a**2 for a in raw_stdscr[0:3]) ** 0.5
        # update gyro
        self.angle_pitch += gyro_x * self.gyro_conv
        self.angle_roll += gyro_y * self.gyro_conv
        yawed = sin(radians(gyro_z * self.gyro_conv))
        self.angle_pitch += self.angle_roll * yawed
        self.angle_roll -= self.angle_pitch * yawed
        # Accelerometer angle
        angle_pitch_accel = degrees(asin(accel_y / accel_vector))
        angle_roll_accel = -degrees(asin(accel_x / accel_vector))
        if self.set_gyro_angles:
            # Drift correction
            self.angle_pitch = self.angle_pitch * 0.98 + angle_pitch_accel * 0.02
            self.angle_roll = self.angle_roll * 0.98 + angle_roll_accel * 0.02
        else:
            # Gyro origin based on gravity
            self.angle_pitch = angle_pitch_accel
            self.angle_roll = angle_roll_accel
            self.set_gyro_angles = True
        # Complementary filter
        self.angle_pitch_output = self.angle_pitch_output * 0.9 + self.angle_pitch * 0.1
        self.angle_roll_output = self.angle_roll_output * 0.9 + self.angle_roll * 0.1

    def tilt(self, _irq=None):
        """Tri-axis tilt sensing using 3-axis accelerometer"""
        raw_accel = list(self.raw())[0:3]
        _g = sum(a**2 for a in raw_accel) ** 0.5
        return [degrees(f(a / _g)) for a, f in zip(raw_accel, (asin, asin, acos))]  # noqa: B905

    def tilt_refin(self, _irq=None):
        """Compute both normalized acceleration-based tilt and roll/pitch angles. Eulor's formula."""
        raw_accel = list(self.raw())[0:3]
        _g = sum(a**2 for a in raw_accel) ** 0.5
        tilt_x, tilt_y, tilt_z = [
            degrees(f(a / _g))
            for a, f in zip(raw_accel, (asin, asin, acos))  # noqa: B905
        ]
        x, y, z = [a / 16384 for a in raw_accel]  # +-2G
        roll = degrees(atan2(y, z))
        pitch = degrees(atan2(x, sqrt(y**2 + z**2)))
        return (tilt_x, tilt_y, tilt_z, x, y, z, roll, pitch)

    def irq_start(self, func):
        """Start IRQ"""
        self._int_pin.irq(trigger=Pin.IRQ_FALLING, handler=func)

    def irq_stop(self):
        """Stop IRQ"""
        self._int_pin.irq(trigger=Pin.IRQ_FALLING)

    def all(self):
        x, y, z = self.tilt()
        return (x, y, z, self.angle_roll_output, self.angle_pitch_output)

    def low_power_mode(self):
        """Put MPU6050 into low power mode."""
        # Set sleep mode and disable gyroscope (bit 5 = 1)
        # https://invensense.tdk.com/wp-content/uploads/2015/02/MPU-6000-Register-Map1.pdf
        self._i2c.writeto_mem(
            self._addr, MPU6050_PWR_MGMT_1, bytes([0x48])
        )  # b'01001000'
        print("MPU6050 is now in low power mode.")

    def register_irq_function(self, func):
        """Register an external function to be called when the interrupt triggers."""
        self._int_pin.irq(trigger=Pin.IRQ_FALLING, handler=func)
        print("New IRQ function registered.")

    def enable_motion_detection(self, threshold=10, trigger_pin=2):
        """
        Enable motion detection with DMP-enabled interrupts.

        Args:
            threshold (int): Sensitivity threshold for motion detection.
            trigger_pin (int): Pin number to trigger when motion is detected.
        """
        self._i2c.writeto_mem(self._addr, MPU6050_USER_CTRL, b"\x04")  # Reset DMP FIFO

        # Enable motion detection in DMP (Interrupt & FIFO)
        self._i2c.writeto_mem(
            self._addr, MPU6050_INT_PIN_CFG, b"\x20"
        )  # Latch INT signal
        self._i2c.writeto_mem(
            self._addr, MPU6050_FIFO_EN, b"\x08"
        )  # Enable FIFO for accel
        self._i2c.writeto_mem(
            self._addr, MPU6050_INT_ENABLE, bytes([0x40])
        )  # Bit 6: Motion Interrupt Enable
        self._i2c.writeto_mem(
            self._addr, 0x1F, bytes([threshold])
        )  # MOT_THR register (1 LSB = 1mg)
        self._i2c.writeto_mem(
            self._addr, 0x20, bytes([1])
        )  # MOT_DUR register (time window)
        self._i2c.writeto_mem(
            self._addr, MPU6050_USER_CTRL, b"\x44"
        )  # Enable DMP + FIFO

        def motion_detected(_irq):
            self._i2c.readfrom_mem(self._addr, MPU6050_INT_STATUS, 1)

        self.register_irq_function(motion_detected)
        print(f"✅ DMP Motion Detection Enabled (Threshold: {threshold})")

    def enable_low_power_dmp_motion_detection(self, threshold=2, sample_rate_div=16):
        """
        Enable DMP motion detection in Low Power Mode.
        Args:
            threshold (int): Sensitivity threshold for motion detection (1 LSB = 1mg).
            sample_rate_div (int): Lower sample rate to reduce power consumption.
        """
        print("🔋 Enabling Low Power Mode with DMP Motion Detection...")

        self._i2c.writeto_mem(
            self._addr, MPU6050_USER_CTRL, b"\x04"
        )  # Reset DMP FIFO & Motion Detection
        self._i2c.writeto_mem(
            self._addr, MPU6050_INT_PIN_CFG, b"\x20"
        )  # Latch INT signal
        self._i2c.writeto_mem(
            self._addr, MPU6050_FIFO_EN, b"\x08"
        )  # Enable FIFO for accel only
        self._i2c.writeto_mem(
            self._addr, MPU6050_INT_ENABLE, bytes([0x40])
        )  # Enable Motion Interrupt
        self._i2c.writeto_mem(
            self._addr, 0x1F, bytes([threshold])
        )  # MOT_THR register (1 LSB = 1mg)
        self._i2c.writeto_mem(
            self._addr, 0x20, bytes([1])
        )  # MOT_DUR register (time window)
        self._i2c.writeto_mem(
            self._addr, MPU6050_SMPRT_DIV, bytes([sample_rate_div])
        )  # Reduce sample rate
        self._i2c.writeto_mem(
            self._addr, MPU6050_USER_CTRL, b"\x44"
        )  # Enable DMP and FIFO again
        self._i2c.writeto_mem(
            self._addr, MPU6050_PWR_MGMT_1, b"\x29"
        )  # Cycle mode (Keep DMP alive)
        self._i2c.writeto_mem(
            self._addr, MPU6050_PWR_MGMT_2, b"\x47"
        )  # Disable Gyro (only accelerometer)
        self._i2c.readfrom_mem(
            self._addr, MPU6050_INT_STATUS, 1
        )  # clear firs interrupt

        print(f"✅ Low Power DMP Motion Detection Enabled (Threshold: {threshold})")

    def configure_for_deep_sleep(self, threshold=2, sample_rate_div=16):
        """Dedicated deep sleep config (called by prepare_for_deep_sleep).

        Puts MPU6050 into the low power + DMP motion detect state used
        to wake via ext0/PIN_WAKE while drawing minimal current.
        """
        self.enable_low_power_dmp_motion_detection(
            threshold=threshold, sample_rate_div=sample_rate_div
        )
        try:  # noqa: SIM105
            self._i2c.readfrom_mem(self._addr, MPU6050_INT_STATUS, 1)
        except Exception:
            pass

    def upload_dmp_firmware(self):
        """Uploads the DMP firmware to the MPU6050."""
        print("Uploading DMP Firmware...")

        # Reset MPU6050 and enable memory write mode
        self._i2c.writeto_mem(self._addr, MPU6050_PWR_MGMT_1, b"\x80")  # Reset device
        sleep_ms(100)
